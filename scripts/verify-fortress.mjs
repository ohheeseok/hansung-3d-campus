import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/Users/heeseokoh/.cache/puppeteer/chrome/mac_arm-131.0.6778.204/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto(process.env.TEST_URL||'http://localhost:3101');
  await expect(page.locator('canvas')).toBeVisible();
  await expect(page.locator('.landmark-label')).toHaveCount(0);
  await page.waitForTimeout(1700);
  await page.screenshot({path:'artifacts/fortress-day.png'});
  await page.getByRole('button',{name:'황혼 모드로 전환'}).click();
  await page.waitForTimeout(600);
  await page.screenshot({path:'artifacts/fortress-dusk.png'});
  await page.getByRole('button',{name:'평면 보기',exact:true}).click();
  await page.waitForTimeout(1400);
  await page.screenshot({path:'artifacts/fortress-top.png'});
  await page.getByRole('button',{name:'전체 보기',exact:true}).click();
  await page.getByRole('button',{name:'지도 레이어',exact:true}).click();
  await page.getByRole('button',{name:'장소 이름',exact:true}).click();
  await expect(page.locator('.landmark-label')).toHaveCount(0);
  await page.getByRole('button',{name:'장소 이름',exact:true}).click();
  await expect(page.locator('.landmark-label')).toHaveCount(0);
  await page.getByRole('button',{name:'나무와 녹지',exact:true}).click();
  await page.getByRole('button',{name:'이동 경로',exact:true}).click();
  await page.screenshot({path:'artifacts/fortress-structure.png'});
  await page.getByRole('button',{name:'나무와 녹지',exact:true}).click();
  await page.getByRole('button',{name:'이동 경로',exact:true}).click();
  await page.getByRole('button',{name:'지도 레이어',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(1600);
  await page.screenshot({path:'artifacts/fortress-mobile.png'});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
  await page.getByRole('button',{name:'장소 목록 열기'}).click();
  await page.getByRole('textbox').fill('미래관');
  await page.locator('.location-row').click();
  await expect(page.locator('.info-panel h2')).toHaveText('미래관');
  await expect(page.locator('a[href*="namu"]')).toHaveCount(0);
  await expect(page.locator('.story-source')).toHaveCount(0);
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync('artifacts/fortress-verification.json',JSON.stringify({testedAt:new Date().toISOString(),checks:['day and dusk screenshots','full scene top view','landscape layer toggles','mobile viewport and selection','no wiki links','no runtime errors'],errors},null,2));
  console.log('PASS fortress views, layers, mobile, no wiki links, no runtime errors');
} finally {await browser.close();}
